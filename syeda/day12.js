// JavaScript Math Object Example

const num = 25.75;

console.log("Original Number:", num);

// Rounding
console.log("Math.round():", Math.round(num));
console.log("Math.floor():", Math.floor(num));
console.log("Math.ceil():", Math.ceil(num));
console.log("Math.trunc():", Math.trunc(num));

// Powers and Roots
console.log("Math.pow(2, 3):", Math.pow(2, 3));
console.log("Math.sqrt(25):", Math.sqrt(25));
console.log("Math.cbrt(27):", Math.cbrt(27));

// Absolute Value
console.log("Math.abs(-10):", Math.abs(-10));

// Maximum and Minimum
console.log("Math.max(10, 20, 30):", Math.max(10, 20, 30));
console.log("Math.min(10, 20, 30):", Math.min(10, 20, 30));

// Random Number
console.log("Random Number:", Math.random());

// Random Integer (1 to 100)
const randomInt = Math.floor(Math.random() * 100) + 1;
console.log("Random Integer:", randomInt);

// Trigonometry
console.log("Math.sin(Math.PI / 2):", Math.sin(Math.PI / 2));
console.log("Math.cos(0):", Math.cos(0));
console.log("Math.tan(Math.PI / 4):", Math.tan(Math.PI / 4));

// Constants
console.log("PI:", Math.PI);
console.log("Euler's Number:", Math.E);

// Logarithms
console.log("Math.log(10):", Math.log(10));
console.log("Math.log10(100):", Math.log10(100));